async function canvasPoint(page,offsetX=0,offsetY=0){
  const box=await page.locator('.map-viewport').boundingBox()
  return{x:box.x+box.width/2+offsetX,y:box.y+box.height/2+offsetY}
}

async function createBlankMap(page,title){
  await page.goto('/')
  await page.getByRole('button',{name:'New map'}).click()
  await page.getByLabel('Map name').fill(title)
  await page.getByRole('button',{name:'Create map'}).click()
  await expect(page.locator('.map-scene-canvas')).toBeVisible({timeout:15000})
  await page.getByRole('button',{name:'Select',exact:true}).click()
  const dismiss=page.getByRole('button',{name:'Dismiss suggestion'})
  if(await dismiss.isVisible())await dismiss.click()
}

