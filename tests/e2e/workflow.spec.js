test('supports temporary Space panning and keyboard history shortcuts',async({page})=>{
  await createBlankMap(page,'Keyboard study')
  const center=await canvasPoint(page),canvas=page.locator('.map-scene-canvas')
  await page.getByRole('button',{name:'Place object'}).click()
  await page.getByTitle(/Treasure chest/).click()
  await page.mouse.click(center.x,center.y)
  await expect(page.getByRole('application')).toHaveAttribute('aria-label',/1 objects/)
  await page.keyboard.press('Control+z')
  await expect(page.getByRole('application')).toHaveAttribute('aria-label',/0 objects/)
  await page.keyboard.press('Control+y')
  await expect(page.getByRole('application')).toHaveAttribute('aria-label',/1 objects/)

  // Non-text controls retain focus after use; they must not disable canvas shortcuts.
  await page.getByRole('button',{name:'Paint terrain'}).click()
  const brushSize=page.getByRole('slider',{name:'Brush diameter'})
  await brushSize.focus()
  await page.keyboard.press('Control+z')
  await expect(page.getByRole('application')).toHaveAttribute('aria-label',/0 objects/)
  await page.keyboard.press('Control+y')
  await expect(page.getByRole('application')).toHaveAttribute('aria-label',/1 objects/)

  await page.keyboard.press('v')
  await expect(page.getByRole('button',{name:'Select'})).toHaveClass(/active/)
  const zoom=page.locator('.zoom-value'),beforeWheel=await zoom.textContent()
  await page.mouse.move(center.x,center.y);await page.mouse.wheel(0,-180)
  await expect(zoom).not.toHaveText(beforeWheel)
  await page.getByRole('button',{name:'Paint terrain'}).click()
  await brushSize.focus()
  const beforePan=await canvas.screenshot()
  await page.keyboard.down('Space')
  await page.mouse.move(center.x,center.y);await page.mouse.down();await page.mouse.move(center.x+110,center.y+70,{steps:5});await page.mouse.up()
  await page.keyboard.up('Space')
  expect(Buffer.compare(await canvas.screenshot(),beforePan)).not.toBe(0)
  await expect(page.getByRole('button',{name:'Paint terrain'})).toHaveClass(/active/)

  const beforeTrackpadPan=await canvas.screenshot(),zoomBeforeTrackpadPan=await zoom.textContent()
  await page.keyboard.down('Space')
  await page.mouse.move(center.x,center.y);await page.mouse.wheel(90,60)
  await page.keyboard.up('Space')
  expect(Buffer.compare(await canvas.screenshot(),beforeTrackpadPan)).not.toBe(0)
  await expect(zoom).toHaveText(zoomBeforeTrackpadPan)

  const beforeSecondaryPan=await canvas.screenshot()
  await page.keyboard.down('Space')
  const contextMenuPrevented=await page.getByRole('application').evaluate((element)=>!element.dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,cancelable:true,button:2})))
  expect(contextMenuPrevented).toBe(true)
  await page.mouse.move(center.x,center.y);await page.mouse.down({button:'right'});await page.mouse.move(center.x-90,center.y-60,{steps:5});await page.mouse.up({button:'right'})
  await page.keyboard.up('Space')
  expect(Buffer.compare(await canvas.screenshot(),beforeSecondaryPan)).not.toBe(0)
})

